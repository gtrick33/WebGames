/**
 * Builds server/ogFont.ts: the letters the link-preview pictures (server/ogImage.ts) are typed with,
 * drawn once here so a Pages Function can set text without a font engine. Latin, Latin-1/Extended-A,
 * Cyrillic and common punctuation, in Inter (SIL Open Font License; the site's own fonts have no
 * Cyrillic), at two weights.
 *
 * Run from glitchbound/: `node scripts/og-font.mjs`. Needs the Inter font installed (fc-list | grep Inter).
 */
import { writeFileSync } from 'node:fs';
import { deflateSync } from 'node:zlib';
import sharp from 'sharp';

const FONTS = [
  { name: 'bold', weight: 800, size: 64 },
  { name: 'text', weight: 600, size: 36 },
];

const range = (a, b) => Array.from({ length: b - a + 1 }, (_, i) => a + i);
const CHARS = [
  ...range(0x20, 0x7e),
  ...range(0xa1, 0xff).filter((c) => c !== 0xad),
  ...range(0x100, 0x17f),
  ...range(0x400, 0x45f),
  0x2013, 0x2014, 0x2018, 0x2019, 0x201c, 0x201d, 0x201e, 0x2022, 0x2026, 0x20ac, 0x2116, 0x2190, 0x2191, 0x2192, 0x2193, 0x25a0, 0x25a1, 0x2713, 0x2717,
];

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const COLS = 20;

/** Renders one text per grid cell; returns the alpha channel and the cell geometry. */
async function grid(texts, weight, size, cellW) {
  const cellH = size * 2;
  const rows = Math.ceil(texts.length / COLS);
  const width = COLS * cellW;
  const height = rows * cellH;
  const body = texts
    .map((t, i) => `<text x="${(i % COLS) * cellW + size}" y="${Math.floor(i / COLS) * cellH + Math.round(size * 1.3)}" xml:space="preserve">${esc(t)}</text>`)
    .join('');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}"><g font-family="Inter" font-weight="${weight}" font-size="${size}" fill="#000">${body}</g></svg>`;
  const { data } = await sharp(Buffer.from(svg)).ensureAlpha().extractChannel(3).raw().toBuffer({ resolveWithObject: true });
  return { data, width, cellW, cellH, origin: (i) => ({ x: (i % COLS) * cellW + size, y: Math.floor(i / COLS) * cellH + Math.round(size * 1.3) }) };
}

/** The inked box of one cell (null when empty). */
function inked(g, i) {
  const x0 = (i % COLS) * g.cellW;
  const y0 = Math.floor(i / COLS) * g.cellH;
  let l = Infinity, r = -1, t = Infinity, b = -1;
  for (let y = y0; y < y0 + g.cellH; y++)
    for (let x = x0; x < x0 + g.cellW; x++)
      if (g.data[y * g.width + x] > 8) {
        l = Math.min(l, x);
        r = Math.max(r, x);
        t = Math.min(t, y);
        b = Math.max(b, y);
      }
  return r < 0 ? null : { l, r, t, b };
}

const parts = [];
for (const f of FONTS) {
  const cellW = f.size * 4;
  const glyphs = await grid(CHARS.map((c) => String.fromCodePoint(c)), f.weight, f.size, cellW);
  // Advances: "H<char>H" against "HH" (straight sides, so kerning stays out of it).
  const pairs = await grid(['HH', ...CHARS.map((c) => `H${String.fromCodePoint(c)}H`)], f.weight, f.size, cellW);
  const hh = inked(pairs, 0).r - pairs.origin(0).x;
  const out = [];
  CHARS.forEach((cp, i) => {
    const pr = inked(pairs, i + 1);
    const adv = pr ? pr.r - pairs.origin(i + 1).x - hh : f.size / 4;
    const box = inked(glyphs, i);
    const o = glyphs.origin(i);
    const w = box ? box.r - box.l + 1 : 0;
    const h = box ? box.b - box.t + 1 : 0;
    const rec = Buffer.alloc(8 + w * h);
    rec.writeUInt16LE(cp, 0);
    rec.writeUInt16LE(Math.max(0, Math.round(adv * 8)), 2);
    rec.writeInt8(box ? box.l - o.x : 0, 4);
    rec.writeInt8(box ? box.t - o.y : 0, 5);
    rec.writeUInt8(w, 6);
    rec.writeUInt8(h, 7);
    // 16 coverage levels (the picture's palette blends in 16 steps anyway): a third of the size.
    for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) rec[8 + y * w + x] = Math.round(glyphs.data[(box.t + y) * glyphs.width + box.l + x] / 17) * 17;
    out.push(rec);
  });
  const packed = deflateSync(Buffer.concat(out), { level: 9 }).toString('base64');
  parts.push(`  ${f.name}: { size: ${f.size}, data: '${packed}' },`);
  console.log(`${f.name}: ${CHARS.length} glyphs, ${Math.round(packed.length / 1024)} KB`);
}

writeFileSync(
  new URL('../server/ogFont.ts', import.meta.url),
  `/* Generated by scripts/og-font.mjs (Inter, SIL Open Font License). Do not edit. */
/**
 * Each font: zlib-deflated records of [code point u16, advance u16 (1/8 px), x offset i8, top
 * offset from the baseline i8, width u8, height u8, then width × height coverage bytes].
 */
export const OG_FONTS = {
${parts.join('\n')}
} as const;
`,
);
