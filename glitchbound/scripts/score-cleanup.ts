/**
 * Turns the registry's score `limits` (src/catalog/games.ts, applied by server/plausible.ts) into the SQL of
 * migration 0015_score_cleanup.sql, which removes leaderboard rows those rules would refuse today.
 *
 * Only hard rules SQL can check are used: a score that isn't a whole number from 0 to 1e9, above the game's
 * maxScore, a stat outside its min/max, a score that contradicts scoreIs/scoreAtMost, and, for runs (which store
 * their start and end), a round shorter than minSeconds or above scorePerSecond × seconds + slack, or a stat
 * above its per-second cap. Rows are copied, whole, into `removed_scores` (with the reason) before they're
 * deleted, so the cleanup can be undone; see the migration's header.
 *
 * Regenerate after changing limits only for a new cleanup migration (0015 is applied once):
 *   node scripts/score-cleanup.ts > migrations/0015_score_cleanup.sql
 */
import { GAMES } from '../src/catalog/games.ts';
import { slackOf } from '../server/plausible.ts';
import type { GameEntry, ScoreLimits } from '../src/catalog/types.ts';

type Rule = [reason: string, condition: string];

const quote = (s: string): string => `'${s.replace(/'/g, "''")}'`;
const stat = (key: string): string => `json_extract(stats, ${quote('$.' + key)})`;
const SECONDS = '((ended_at - started_at) / 1000.0)';

/** The rules of one game, in the order refusal() checks them. `timed`: the row stores its start and end (runs). */
function gameRules(l: ScoreLimits, timed: boolean): Rule[] {
  const rules: Rule[] = [];
  if (timed) rules.push(['too_fast', `${SECONDS} < ${l.minSeconds ?? 1}`]);
  if (l.maxScore !== undefined) rules.push(['above_max', `score > ${l.maxScore}`]);
  if (timed) rules.push(['implausible_score', `score > ${l.scorePerSecond} * ${SECONDS} + ${slackOf(l)}`]);
  for (const [key, cap] of Object.entries(l.stats ?? {})) {
    if (cap.min !== undefined) rules.push(['bad_stats', `${stat(key)} < ${cap.min}`]);
    if (cap.max !== undefined) rules.push(['bad_stats', `${stat(key)} > ${cap.max}`]);
    if (timed && cap.perSecond !== undefined) {
      rules.push(['bad_stats', `${stat(key)} > ${cap.perSecond} * ${SECONDS} + ${Math.max(1, Math.min(50, 10 * cap.perSecond))}`]);
    }
  }
  // Like refusal(), only when the row reports every stat of the sum (a missing one is NULL, so nothing is removed).
  const sum = (weights: Record<string, number>): string => Object.entries(weights).map(([k, w]) => `${w} * ${stat(k)}`).join(' + ');
  if (l.scoreIs) rules.push(['bad_stats', `score <> ${sum(l.scoreIs)}`]);
  if (l.scoreAtMost) rules.push(['implausible_score', `score > ${sum(l.scoreAtMost)}`]);
  return rules;
}

/** A CASE expression naming why a row breaks a rule, or NULL for a row that keeps its place. */
function reasonOf(games: GameEntry[], timed: boolean): string {
  const lines = [`WHEN typeof(score) <> 'integer' OR score < 0 OR score > 1000000000 THEN 'bad_score'`];
  for (const g of games) {
    if (!g.limits) continue;
    for (const [reason, condition] of gameRules(g.limits, timed)) lines.push(`WHEN game = ${quote(g.slug)} AND ${condition} THEN ${quote(reason)}`);
  }
  return `CASE\n      ${lines.join('\n      ')}\n    END`;
}

export function cleanupSql(games: GameEntry[] = GAMES): string {
  return `-- Generated by scripts/score-cleanup.ts from the registry's score limits (PR #96). Do not edit by hand.
--
-- Removes leaderboard rows that today's score rules (server/plausible.ts) would refuse: finished runs (the weekly
-- board) and personal bests (the all-time board). Each removed row is first copied whole into removed_scores
-- with its reason. A player whose best was removed gets their best remaining finished run as their best.
--
-- To undo (restores every removed row; a rebuilt best is replaced by the original):
--   INSERT OR IGNORE INTO runs (id, user_id, game, started_at, ended_at, score, stats, day, new_best, status)
--     SELECT id, user_id, game, started_at, ended_at, score, stats, day, new_best, status FROM removed_scores WHERE source = 'runs';
--   INSERT OR REPLACE INTO bests (user_id, game, score, stats, at)
--     SELECT user_id, game, score, stats, at FROM removed_scores WHERE source = 'bests';

CREATE TABLE IF NOT EXISTS removed_scores (
  source TEXT NOT NULL,      -- the table the row came from: runs | bests
  reason TEXT NOT NULL,      -- bad_score | too_fast | above_max | implausible_score | bad_stats | run_removed
  removed_at INTEGER NOT NULL,
  id TEXT,                   -- runs
  user_id TEXT NOT NULL,
  game TEXT NOT NULL,
  started_at INTEGER,        -- runs
  ended_at INTEGER,          -- runs
  score,                     -- kept exactly as stored (no type, so a non-integer stays as it was)
  stats TEXT,
  day TEXT,                  -- runs
  new_best INTEGER,          -- runs
  status TEXT,               -- runs
  at INTEGER                 -- bests
);

-- Finished runs.
INSERT INTO removed_scores (source, reason, removed_at, id, user_id, game, started_at, ended_at, score, stats, day, new_best, status)
SELECT 'runs', reason, CAST(strftime('%s', 'now') AS INTEGER) * 1000, id, user_id, game, started_at, ended_at, score, stats, day, new_best, status
FROM (
  SELECT runs.*, ${reasonOf(games, true)} AS reason
  FROM runs WHERE status = 'ok'
) WHERE reason IS NOT NULL;

DELETE FROM runs WHERE status = 'ok' AND id IN (SELECT id FROM removed_scores WHERE source = 'runs');

-- Personal bests: by their own score and stats, or because the run they came from was removed.
INSERT INTO removed_scores (source, reason, removed_at, user_id, game, score, stats, at)
SELECT 'bests', reason, CAST(strftime('%s', 'now') AS INTEGER) * 1000, user_id, game, score, stats, at
FROM (
  SELECT b.*, COALESCE(${reasonOf(games, false).replace(/\n/g, '\n  ')},
    (SELECT 'run_removed' FROM removed_scores r
      WHERE r.source = 'runs' AND r.user_id = b.user_id AND r.game = b.game AND r.score = b.score AND r.ended_at = b.at)) AS reason
  FROM bests b
) WHERE reason IS NOT NULL;

DELETE FROM bests WHERE EXISTS (
  SELECT 1 FROM removed_scores r
  WHERE r.source = 'bests' AND r.user_id = bests.user_id AND r.game = bests.game AND r.score IS bests.score AND r.at = bests.at
);

-- The best remaining finished run (highest score, earliest first) takes a removed best's place.
INSERT OR IGNORE INTO bests (user_id, game, score, stats, at)
SELECT user_id, game, score, stats, ended_at FROM (
  SELECT user_id, game, score, COALESCE(stats, '{}') AS stats, ended_at,
    ROW_NUMBER() OVER (PARTITION BY user_id, game ORDER BY score DESC, ended_at ASC) AS n
  FROM runs
  WHERE status = 'ok' AND score > 0
    AND EXISTS (SELECT 1 FROM removed_scores r WHERE r.source = 'bests' AND r.user_id = runs.user_id AND r.game = runs.game)
) WHERE n = 1;
`;
}

if (import.meta.url === `file://${process.argv[1]}`) process.stdout.write(cleanupSql());
