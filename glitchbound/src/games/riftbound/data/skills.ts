import type { SkillDef, SkillSpec } from './types';

/** A spec with neutral defaults, so each skill only lists what makes it itself. */
export function spec(p: Partial<SkillSpec> & Pick<SkillSpec, 'id' | 'cast'>): SkillSpec {
  return {
    aim: 'direction',
    range: 100,
    cooldown: 1,
    charges: 1,
    damage: 0,
    dmgType: 'physical',
    windup: 0,
    speed: 0,
    radius: 3,
    count: 1,
    spread: 0,
    pierce: 0,
    bounce: 0,
    area: 0,
    arc: 0,
    duration: 0,
    tick: 0,
    knock: 0,
    onHit: [],
    onImpact: [],
    onKill: [],
    onCast: [],
    bonusVs: [],
    extra: {},
    tags: [],
    ...p,
  };
}

