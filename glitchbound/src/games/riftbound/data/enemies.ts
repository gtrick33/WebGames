/** Health and damage multipliers for an enemy level. */
export const enemyScale = (level: number): { hp: number; dmg: number; xp: number } => ({
  hp: 1 + 0.22 * (level - 1),
  dmg: 1 + 0.14 * (level - 1),
  xp: 1 + 0.15 * (level - 1),
});
