/** Polska liczba mnoga po liczebniku: 1 pytanie, 2 pytania, 5 pytań (i 22 pytania, ale 12 pytań). */
export const plural = (n: number, one: string, few: string, many: string): string => {
  if (n === 1) return one;
  const units = n % 10;
  const tens = n % 100;
  return units >= 2 && units <= 4 && (tens < 12 || tens > 14) ? few : many;
};

