/** Româna pune „de” între număr și substantiv de la 20 în sus (20 de întrebări), dar nu după 1–19 la final (101 întrebări). */
export const de = (n: number): string => (n % 100 >= 20 || (n >= 100 && n % 100 === 0) ? 'de ' : '');

/** Același „de” pentru un număr deja formatat („1.300”). */
const deText = (s: string): string => de(Number(s.replace(/\D/g, '')));

